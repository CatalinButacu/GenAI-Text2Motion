# .\.venv\Scripts\python.exe scripts/licenses/collect_licenses.py
from __future__ import annotations

import json
import re
import tomllib
from datetime import date
from importlib import metadata
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PYPROJECT = REPO / "pyproject.toml"
VERIFIED_ASSETS = REPO / "licenses" / "verified_assets.json"
REPORT = REPO / "THIRD_PARTY_LICENSES.md"
REQUIRED_FIELDS = (
    "name",
    "used_for",
    "licence",
    "commercial_use",
    "source_url",
    "verified_on",
    "evidence",
)
MAX_LICENCE_CHARS = 90


def requirement_name(requirement: str) -> str:
    match = re.match(r"[A-Za-z0-9_.\-]+", requirement.strip())
    if match is None:
        raise ValueError(f"cannot read a package name from {requirement!r}")
    return match.group(0)


def declared_dependencies() -> dict[str, list[str]]:
    project = tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))["project"]
    groups = {"runtime": project["dependencies"]}
    for group_name, requirements in project.get("optional-dependencies", {}).items():
        groups[group_name] = requirements
    return {
        group_name: sorted({requirement_name(requirement) for requirement in requirements})
        for group_name, requirements in groups.items()
    }


def package_licence(package: str) -> tuple[str, str]:
    package_metadata = metadata.metadata(package)
    version = package_metadata["Version"]
    expression = package_metadata.get("License-Expression")
    if expression:
        return version, expression
    classifiers = [
        value.split("::")[-1].strip()
        for value in package_metadata.get_all("Classifier") or []
        if value.startswith("License ::")
    ]
    if classifiers:
        return version, "; ".join(classifiers)
    licence_text = (package_metadata.get("License") or "").strip()
    if licence_text:
        first_line = licence_text.splitlines()[0].strip()
        return version, first_line[:MAX_LICENCE_CHARS]
    return version, "NOT DECLARED in the package metadata"


def verified_assets() -> list[dict]:
    records = json.loads(VERIFIED_ASSETS.read_text(encoding="utf-8"))
    for record in records:
        missing = [name for name in REQUIRED_FIELDS if not str(record.get(name, "")).strip()]
        if missing:
            raise ValueError(f"asset {record.get('name')!r} has no value for {missing}")
        if not record["source_url"].startswith("https://"):
            raise ValueError(f"asset {record['name']!r} needs an https source_url")
        date.fromisoformat(record["verified_on"])
    return records


def render_report() -> str:
    lines = [
        "# Third-party licences",
        "",
        "This file is generated by `scripts/licenses/collect_licenses.py`. Do not edit it by hand.",
        "",
        "## Data sets, models and ported code",
        "",
        "Each row is in `licenses/verified_assets.json`. A row is permitted only with a source URL,",
        "the date of the check, and a sentence copied from that source.",
        "",
        "| Asset | Used for | Licence | Commercial use | Checked on | Source |",
        "|---|---|---|---|---|---|",
    ]
    for record in verified_assets():
        lines.append(
            f"| {record['name']} | {record['used_for']} | {record['licence']} "
            f"| {record['commercial_use']} | {record['verified_on']} | {record['source_url']} |"
        )
    lines.extend(["", "Evidence, copied from each source:", ""])
    for record in verified_assets():
        lines.append(f'- **{record["name"]}:** "{record["evidence"]}"')
    lines.extend(
        [
            "",
            "## Python packages",
            "",
            "Direct dependencies from `pyproject.toml`. The licence is read from the metadata of the",
            "installed package. It is the statement of the package author, not a legal review.",
            "",
            "| Group | Package | Installed version | Licence in the package metadata |",
            "|---|---|---|---|",
        ]
    )
    for group_name, packages in declared_dependencies().items():
        for package in packages:
            version, licence = package_licence(package)
            lines.append(f"| {group_name} | {package} | {version} | {licence} |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    report = render_report()
    REPORT.write_text(report, encoding="utf-8", newline="\n")
    print(f"wrote {REPORT.relative_to(REPO)} ({len(report.splitlines())} lines)")


if __name__ == "__main__":
    main()
